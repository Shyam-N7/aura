import { describe, it, expect } from 'vitest';
import {
  parseVideo,
  parseArtTrackDescription,
  cleanTitle,
  extractMovie,
  topicChannelArtist,
  SOURCE,
} from './ytTrackParse.js';
import {
  matchVideo,
  scoreCandidate,
  fingerprint,
  fingerprintKeys,
  TIER,
} from './ytMatch.js';

// A JioSaavn candidate in `mapSong` shape (catalog.js:82). `artist` is ONE
// string but often a comma-joined list, and `language` is passed through raw —
// both are why the scorer tokenises and lowercases rather than comparing whole
// strings.
const song = o => ({
  id: 'x',
  title: '',
  artist: '',
  album: null,
  language: null,
  durationSec: null,
  ...o,
});

const ART_DESC = `Provided to YouTube by Universal Music Group

Kesariya (From "Brahmastra") · Pritam · Arijit Singh · Amitabh Bhattacharya

Brahmastra

℗ 2022 Sony Music Entertainment India Pvt. Ltd.

Released on: 2022-07-17

Auto-generated by YouTube.`;

describe('tier 1 — Art Track descriptions', () => {
  it('reads track, artists, album and year from the credit block', () => {
    const r = parseArtTrackDescription(ART_DESC);
    expect(r.title).toBe('Kesariya');
    expect(r.artists).toEqual(['Pritam', 'Arijit Singh', 'Amitabh Bhattacharya']);
    expect(r.album).toBe('Brahmastra');
    expect(r.year).toBe(2022);
  });

  it('returns null when the block is absent, so tier 2 can take over', () => {
    expect(parseArtTrackDescription('just a normal description')).toBeNull();
  });

  it('marks the source so duration can be trusted differently', () => {
    const p = parseVideo({
      title: 'anything',
      channelTitle: 'Pritam - Topic',
      description: ART_DESC,
    });
    expect(p.source).toBe(SOURCE.ART_TRACK);
    expect(p.title).toBe('Kesariya');
  });

  it('reads a Topic channel as a high-confidence artist', () => {
    expect(topicChannelArtist('Arijit Singh - Topic')).toBe('Arijit Singh');
    expect(topicChannelArtist('T-Series')).toBeNull();
  });
});

